<h3>OpenPGP and Email</h3>

<p>It is best practice to encrypt all emails using OpenPGP. This ensures only the sender and recipient have access to the contents of the encrypted email.</p>

<p>When sending us your encrypting email, you will need our OpenPGP public key. If your mail client doesn't automatically find our public key, you may download it from <a href="/resources/2FE99534BAD033691B798BCCADC3FDBE0F817816.asc" title="download our public key via itzzen.net">itzzen.net (this very website!)</a> or <a href="https://keys.openpgp.org/vks/v1/by-fingerprint/2FE99534BAD033691B798BCCADC3FDBE0F817816" title="download our public key via keys.openpgp.org">keys.openpgp.org</a>.</p>

<p>If you wish for further details on OpenPGP and how to use it, <a href="https://help.riseup.net/en/security/message-security/openpgp" title="go to the riseup openpgp help page">this is a pretty good guide</a></p>

